package convert_test

import (
	"go/ast"
	"go/parser"
	"go/token"
	"io/fs"
	"path/filepath"
	"strconv"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

const modulePath = "github.com/altessa-s/go-convert"

// layers lists, per package directory pattern, the module packages it may
// import. Dependencies point inward: adapters (codec/*, proto) depend on the
// codec contract, the facade depends on the engine, and the engine depends on
// leaf internals only. A trailing "/*" matches any subdirectory.
var layers = []struct {
	dir     string
	imports []string
}{
	{".", []string{"codec", "internal/engine"}},
	{"codec", nil},
	{"codec/*", []string{"codec", "internal/reflect"}},
	{"converttest", []string{"."}},
	{"internal/engine", []string{"codec", "internal/primitive", "internal/reflect", "internal/typeinfo"}},
	{"internal/primitive", []string{"internal/reflect"}},
	{"internal/reflect", nil},
	{"internal/typeinfo", nil},
	{"proto/codec/*", []string{"codec", "internal/reflect", "proto/codec/*"}},
	{"googletype", []string{"codec", "internal/reflect"}},
}

func TestArchitecture(t *testing.T) {
	t.Parallel()

	err := filepath.WalkDir(".", func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			if path != "." && (strings.HasPrefix(entry.Name(), ".") || entry.Name() == "devtools" || entry.Name() == "bin") {
				return filepath.SkipDir
			}
			return nil
		}
		if filepath.Ext(path) != ".go" {
			return nil
		}
		checkFile(t, path)
		return nil
	})
	require.NoError(t, err)
}

func checkFile(t *testing.T, path string) {
	t.Helper()

	file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ParseComments)
	require.NoError(t, err)
	dir := filepath.ToSlash(filepath.Dir(path))
	isTest := strings.HasSuffix(path, "_test.go")

	for _, imp := range file.Imports {
		imported, err := strconv.Unquote(imp.Path.Value)
		require.NoError(t, err)
		if dir == "." || !strings.HasPrefix(dir, "proto") {
			require.NotContains(t, imported, "google.golang.org/protobuf", "%s: the root module must not depend on protobuf", path)
		}
		if !isTest {
			require.True(t, importAllowed(dir, imported), "%s imports %s across a layer boundary", path, imported)
		}
	}

	for _, decl := range file.Decls {
		switch decl := decl.(type) {
		case *ast.FuncDecl:
			if decl.Recv == nil && decl.Name.Name == "init" {
				require.Fail(t, "package init functions are forbidden", path)
			}
			if decl.Recv == nil && strings.HasPrefix(decl.Name.Name, "With") && !isTest {
				base := filepath.Base(path)
				require.True(t, base == "options.go" || base == "options_gen.go", "%s: functional options belong in options.go", path)
				if base == "options_gen.go" {
					require.True(t, hasGeneratedHeader(file), "%s must be generated by optgen", path)
				}
			}
		case *ast.GenDecl:
			if decl.Tok != token.VAR {
				continue
			}
			for _, spec := range decl.Specs {
				for _, name := range spec.(*ast.ValueSpec).Names {
					require.False(t, ast.IsExported(name.Name), "%s: exported variable %s is forbidden", path, name.Name)
				}
			}
		}
	}

	if !isTest && file.Name.Name != "main" {
		require.FileExists(t, filepath.Join(filepath.Dir(path), "doc.go"))
	}
}

func importAllowed(dir, imported string) bool {
	rel, ok := strings.CutPrefix(imported, modulePath)
	if !ok {
		return true
	}
	rel = strings.TrimPrefix(rel, "/")
	if rel == "" {
		rel = "."
	}
	for _, layer := range layers {
		if !matchDir(layer.dir, dir) {
			continue
		}
		for _, allowed := range layer.imports {
			if matchDir(allowed, rel) {
				return true
			}
		}
		return false
	}
	return false
}

func matchDir(pattern, dir string) bool {
	if prefix, ok := strings.CutSuffix(pattern, "/*"); ok {
		return strings.HasPrefix(dir, prefix+"/")
	}
	return pattern == dir
}

func hasGeneratedHeader(file *ast.File) bool {
	for _, group := range file.Comments {
		if strings.Contains(group.Text(), "Code generated by optgen. DO NOT EDIT.") {
			return true
		}
	}
	return false
}
